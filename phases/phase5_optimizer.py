"""BUILD LOOKUP DICTIONARIES

Converts DataFrames into fast dictionary lookups so the simulation loops below don't repeatedly filter DataFrames
"""

def min_stint_by_circuit(raw_laps):
    '''Shortest stint the optimizer may plan at each circuit: the 10th percentile of the
    opening stints teams really ran there in 2024, never below MIN_STINT_LENGTH.
    Opening stints that went the whole race (no stop) are left out.'''
    dry = raw_laps[raw_laps['Compound'].isin(['SOFT', 'MEDIUM', 'HARD'])]
    stints = dry.groupby(['CircuitName', 'Driver', 'Stint'])['LapNumber'].agg(['min', 'max', 'size'])
    race_laps = dry.groupby('CircuitName')['LapNumber'].max()
    stints = stints.join(race_laps.rename('race'), on='CircuitName')
    opening = stints[(stints['min'] == 1) & (stints['max'] < stints['race'])]
    floor = opening.groupby('CircuitName')['size'].quantile(OPENING_STINT_PERCENTILE).round()
    return {c: max(MIN_STINT_LENGTH, int(v)) for c, v in floor.items()}

def measured_stop_costs(raw_laps):
    '''Time each green-flag stop really cost in 2024: the in-lap, out-lap and next three
    laps, against the driver's own median green-flag pace in the five laps either side.
    Stops with a Safety Car, VSC or yellow anywhere in that window are left out.'''
    r = raw_laps.copy()
    r['LapNumber'] = r['LapNumber'].astype(int)
    r['TrackStatus'] = r['TrackStatus'].astype(str).str.replace(r'\.0$', '', regex=True)
    rows = []
    for _, g in r.groupby(['CircuitName', 'Driver']):
        g = g.drop_duplicates('LapNumber').set_index('LapNumber').sort_index()
        for lap in g.index[g['IsPitInLap'] == True]:
            window = list(range(lap, lap + 5))
            if not all(l in g.index for l in window):
                continue
            w = g.loc[window]
            ref = g.loc[[l for l in list(range(lap - 5, lap)) + list(range(lap + 6, lap + 11)) if l in g.index]]
            ref = ref[(ref['TrackStatus'] == '1') & (ref['IsPitInLap'] != True) & (ref['IsPitOutLap'] != True)]
            if w['TrackStatus'].ne('1').any() or len(ref) < 4 or w['LapTimeSeconds'].isna().any():
                continue
            rows.append({'lap': lap, 'cost': (w['LapTimeSeconds'] - ref['LapTimeSeconds'].median()).sum()})
    return pd.DataFrame(rows, columns=['lap', 'cost'])

def early_stop_cost(raw_laps):
    '''Extra time a stop on the opening laps cost in 2024 compared with a later stop
    (the field is still bunched, so you rejoin in traffic). 0 if the data is too thin.'''
    costs = measured_stop_costs(raw_laps)
    early = costs[costs['lap'] <= EARLY_STOP_LAPS]['cost']
    later = costs[costs['lap'] > EARLY_STOP_LAPS]['cost']
    extra = max(0.0, early.median() - later.median()) if len(early) >= MIN_EARLY_STOPS else 0.0
    log.info(f" Measured green-flag stops: {len(costs)}; stops on laps 1-{EARLY_STOP_LAPS} cost "
             f"{extra:+.1f}s more than later ones (from {len(early)} early stops"
             f"{', a thin sample' if len(early) < 30 else ''})")
    return round(extra, 2)

def build_lookups(degradation_df, feature_store, hazard_df, engineered_laps, raw_laps):
    log.info("BUILDING LOOKUP STRUCTURES...")

    #degradation_profiles -> {circuit: {compound: {rate, avg_lap_time, base_lap_time, max_tyre_life}}}
    deg_lookup = {}
    for _, row in degradation_df.iterrows():
        circuit = row['CircuitName']
        compound = row['Compound']

        #A negative rate would make the tyre "improve" with age, so clamp at 0
        rate = max(row['DegradationRate'], 0.0)

        '''Fresh-tyre pace: the fuel-corrected average lap (so a compound run late on a
        light car doesn't look faster than it is) minus the average wear over a stint'''
        pace = row['AvgFuelCorrectedLapTime'] if 'AvgFuelCorrectedLapTime' in row else row['AvgLapTime']
        deg_lookup.setdefault(circuit, {})[compound] = {
            'degradation_rate': rate,
            'avg_lap_time': row['AvgLapTime'],
            'base_lap_time': pace - rate * row['AvgTyreLife'],
            'max_tyre_life': row['AvgTyreLife'] * 2 #Roughly safety ceiling
        }

    # feature_store -> {circuit: {pit_loss, early_stop_cost, sc_probability, total_laps, min_stint}}
    min_stint = min_stint_by_circuit(raw_laps)
    early_cost = early_stop_cost(raw_laps)
    circuit_info = {}
    for _, row in feature_store.iterrows():
        circuit_info[row['CircuitName']] = {
            'pit_loss': row['AvgPitLoss'] if pd.notna(row['AvgPitLoss']) else DEFAULT_PIT_LOSS,
            'early_stop_cost': early_cost,
            'sc_probability': row['SafetyCarProbability'],
            'total_laps': int(row['TotalRaceLaps']),
            'min_stint': min_stint.get(row['CircuitName'], MIN_STINT_LENGTH)
        }

    # cox_hazard -> {circuit: {covariate: hazard_ratio}}
    hazard_lookup = {}
    for _, row in hazard_df.iterrows():
        hazard_lookup.setdefault(row['CircuitName'], {})[row['Covariate']] = row['HazardRatio']

    log.info(f" Circuits with degradation data: {len(deg_lookup)}")
    log.info(f" Circuits with circuit info: {len(circuit_info)}")
    log.info(f" Circuits with hazard data: {len(hazard_lookup)}")

    return deg_lookup, circuit_info, hazard_lookup

"""STINT TIME CALCULATION

Uses the arithmetic series formula to sum oredicted lap times across a stint without looping lap by lap
"""

def stint_time(base_lap_time, degradation_rate, stint_length):
    '''Lap k of a stint takes base_lap_time + degradation_rate * k,
    so the stint total is the sum of that over k = 1..stint_length'''
    total = stint_length * base_lap_time
    total += degradation_rate * (stint_length * (stint_length + 1) / 2)
    return total

def is_valid_stint(profile, stint_length, min_stint=MIN_STINT_LENGTH):
    if stint_length < min_stint:
        return False
    max_allowed = profile['max_tyre_life'] + EXTRAPOLATION_BUFFER
    if stint_length > max_allowed:
        return False
    return True

"""RISK SCORE CALCULATION

Uses the Cox Hazard Ratio for CompoundEncoder (a proxy for how much compound choice affects failure risk at this circuit) combined with how far eachs tint pushes the compound's typical stint length, to produce a 0-100 risk score

Higher score = higher strategic risk
"""

def calculate_risk_score(circuit, strategy, deg_profiles, hazard_lookup, sc_probability):
    hazard_info = hazard_lookup.get(circuit, {})
    compound_hazard = hazard_info.get('CompoundEncoded', 1.0)

    overrun_penalty = 0
    for compound, stint_length in strategy:
        profile = deg_profiles.get(compound)
        if profile is None:
            continue
        typical_max = profile['max_tyre_life']
        if stint_length > typical_max:
            overrun_penalty += (stint_length - typical_max) * 2

    '''Base risk from safety car probability (more SC = more
    strategic uncertainity regardless of tire choice)'''
    sc_risk = sc_probability * 40

    #Hazard ratio contribution - scaled to a reasonable range
    hazard_risk = min(abs(compound_hazard - 1.0) * 20, 30)

    total_risk = sc_risk + hazard_risk + overrun_penalty
    return round(min(total_risk, 100), 1)

"""STRATEGY SIMULATION
"""

def simulate_strategy(circuit, strategy, deg_profiles, pit_loss, min_stint=MIN_STINT_LENGTH, early_cost=0.0,
                      check_limits=True):
    total_time = 0
    num_stops = len(strategy) - 1

    for compound, stint_length in strategy:
        profile = deg_profiles.get(compound)
        if profile is None:
            return None
        if check_limits and not is_valid_stint(profile, stint_length, min_stint):
            return None
        total_time += stint_time(
            profile['base_lap_time'], profile['degradation_rate'], stint_length
        )
    total_time += num_stops * pit_loss

    #A stop on the opening laps costs extra: you rejoin a field that's still bunched up
    stop_laps = np.cumsum([length for _, length in strategy])[:-1]
    total_time += early_cost * int((stop_laps <= EARLY_STOP_LAPS).sum())

    '''Pace is fuel-corrected, so take the fuel effect back out: lap L of the race is
    FUEL_EFFECT_PER_LAP * L faster. It's the same for every strategy over the same
    distance, so it never changes which plan wins, only the predicted race time'''
    race_laps = sum(length for _, length in strategy)
    total_time -= FUEL_EFFECT_PER_LAP * race_laps * (race_laps + 1) / 2
    return total_time

"""FIND ALL VALID STRATEGIES FOR A CIRCUIT
"""

def generate_strategies(circuit, deg_lookup, circuit_info):
    '''Every valid 1-, 2- and 3-stop strategy, as {stops: [{strategy, total_time}, ...]}.
    Stints are at least the circuit's min_stint, and every strategy uses 2+ compounds.'''
    if circuit not in circuit_info or circuit not in deg_lookup:
        return {}, None

    total_laps = circuit_info[circuit]['total_laps']
    pit_loss = circuit_info[circuit]['pit_loss']
    min_stint = circuit_info[circuit]['min_stint']
    early_cost = circuit_info[circuit].get('early_stop_cost', 0.0)
    deg_profiles = deg_lookup[circuit]
    available_compounds = list(deg_profiles.keys())

    results = {1: [], 2: [], 3: []}

    def add(stops, strategy):
        if len({c for c, _ in strategy}) < 2:           #must use at least two compounds
            return
        total_time = simulate_strategy(circuit, strategy, deg_profiles, pit_loss, min_stint, early_cost)
        if total_time is not None:
            results[stops].append({'strategy': strategy, 'total_time': total_time})

    #1-STOP
    for s1 in range(min_stint, total_laps - min_stint + 1):
        s2 = total_laps - s1
        for c1 in available_compounds:
            for c2 in available_compounds:
                add(1, [(c1, s1), (c2, s2)])

    #2-STOP
    for s1 in range(min_stint, total_laps - 2 * min_stint + 1, TWO_STOP_STEP):
        for s2 in range(min_stint, total_laps - s1 - min_stint + 1, TWO_STOP_STEP):
            s3 = total_laps - s1 - s2
            if s3 < min_stint:
                continue
            for c1 in available_compounds:
                for c2 in available_compounds:
                    for c3 in available_compounds:
                        add(2, [(c1, s1), (c2, s2), (c3, s3)])

    #3-STOP
    for s1 in range(min_stint, total_laps - 3 * min_stint + 1, THREE_STOP_STEP):
        for s2 in range(min_stint, total_laps - s1 - 2 * min_stint + 1, THREE_STOP_STEP):
            for s3 in range(min_stint, total_laps - s1 - s2 - min_stint + 1, THREE_STOP_STEP):
                s4 = total_laps - s1 - s2 - s3
                if s4 < min_stint:
                    continue
                for c1 in available_compounds:
                    for c2 in available_compounds:
                        for c3 in available_compounds:
                            for c4 in available_compounds:
                                add(3, [(c1, s1), (c2, s2), (c3, s3), (c4, s4)])

    return results, deg_profiles

"""FIND REAL-WORLD MOST COMMON STRATEGY(for Plan B)

Looks at the actual 2024 stint data to find what stop-count and rough compounds sequence was commonly used at this circuit.
It reads the raw laps of drivers who finished the full distance: the cleaned laps drop whole stints (wet running,
red-flag and safety-car laps), so their stint count doesn't match the stops a driver really made
"""

def find_real_world_strategy(circuit, raw_laps):
    circuit_laps = raw_laps[raw_laps['CircuitName'] == circuit].dropna(subset=['LapNumber', 'Stint'])

    if circuit_laps.empty:
        return None

    race_laps = circuit_laps['LapNumber'].max()
    sequences = []
    lengths_by_seq = {}
    for _, driver_laps in circuit_laps.groupby('Driver'):
        if driver_laps['LapNumber'].max() < race_laps:      #retired or lapped: not a full-race strategy
            continue
        stints = driver_laps.sort_values('LapNumber').groupby('Stint')
        compounds = stints['Compound'].first().tolist()
        spans = (stints['LapNumber'].max() - stints['LapNumber'].min() + 1).astype(int).tolist()

        '''Fold stints of 1-2 laps into the next one: tyres changed under a lap-1 red flag
        (Japan, Monaco) and stint-numbering glitches aren't pit stops'''
        seq, lengths, carry = [], [], 0
        for compound, n in zip(compounds, spans):
            if n <= 2:
                carry += n
                continue
            seq.append(compound)
            lengths.append(n + carry)
            carry = 0
        if not seq:
            continue
        lengths[-1] += carry

        seq = tuple(seq)
        sequences.append(seq)
        lengths_by_seq.setdefault(seq, []).append(lengths)

    if not sequences:
        return None

    #Most common stop count, then the most common compound sequence among drivers who made it
    stop_counts = pd.Series([len(s) - 1 for s in sequences])
    common_stop_count = int(stop_counts.mode().iloc[0])
    best_seq = pd.Series([s for s in sequences if len(s) - 1 == common_stop_count]).mode().iloc[0]

    #Median stint length at each position, across drivers who ran this sequence
    median_lengths = np.median(np.array(lengths_by_seq[best_seq]), axis=0)

    return {
        'stop_count': common_stop_count,
        'compound_sequence': list(best_seq),
        'stint_lengths': median_lengths.tolist()
    }

"""BUILD PLAN A/B/C FOR ONE CIRCUIT
"""

def build_plans(circuit, deg_look, circuit_info, hazard_lookup, raw_laps):
    by_stops, deg_profiles = generate_strategies(circuit, deg_look, circuit_info)
    if not any(by_stops.values()) and circuit_info.get(circuit, {}).get('min_stint', MIN_STINT_LENGTH) > MIN_STINT_LENGTH:
        '''The circuit's floor can rule out every strategy (Great Britain 2024 was wet, so
        its few dry opening stints were long). Fall back to the general minimum'''
        log.warning(f" {circuit}: nothing fits with a {circuit_info[circuit]['min_stint']}-lap minimum stint, "
                    f"retrying with {MIN_STINT_LENGTH}")
        circuit_info[circuit]['min_stint'] = MIN_STINT_LENGTH
        by_stops, deg_profiles = generate_strategies(circuit, deg_look, circuit_info)

    def pick(results):
        '''The fastest plan, except that plans within TIE_TOLERANCE of it are a tie at the
        model's accuracy: among those, prefer the one whose shortest stint is longest.
        (With flat tyre wear, e.g. Monaco and Canada, a 5-lap and a 10-lap opening stint
        can differ by under a second, and "fastest" would just pick the extreme.)'''
        fastest = min(r['total_time'] for r in results)
        near = [r for r in results if r['total_time'] <= fastest + TIE_TOLERANCE]
        return max(near, key=lambda r: (min(n for _, n in r['strategy']), -r['total_time']))

    best = {stops: pick(r) for stops, r in by_stops.items() if r}

    if not best:
        return None

    sc_probability = circuit_info[circuit]['sc_probability']

    #PLAN-A: optimal overall (ties broken the same way)
    plan_a = pick(list(best.values()))

    '''PLAN-C: the fastest strategy with a different number of stops. Where no
    one-stop fits the tyre life seen in 2024, that is usually a three-stop'''
    plan_a_stops = len(plan_a['strategy']) - 1
    others = [plan for stops, plan in best.items() if stops != plan_a_stops]
    plan_c = min(others, key=lambda x: x['total_time']) if others else None

    #PLAN-B: Most common real-world strategy
    real_world = find_real_world_strategy(circuit, raw_laps)
    plan_b = None

    if real_world is not None:
        total_laps = circuit_info[circuit]['total_laps']

        '''Use the real median stint lengths, scaled so they add up
        to the full race distance (medians of each stint needn't sum
        to exactly the race length)'''
        raw = np.array(real_world['stint_lengths'], dtype=float)
        lengths = np.round(raw / raw.sum() * total_laps).astype(int)
        lengths[-1] = total_laps - lengths[:-1].sum()

        approx_strategy = list(zip(real_world['compound_sequence'], lengths.tolist()))

        '''No stint-length limits here: teams really ran these stints, even past the tyre
        life in the cleaned laps. Plans are dry-tyre only, so a race run partly on
        intermediates (Canada, Great Britain) has no Plan B rather than a copy of another plan'''
        total_time = simulate_strategy(
            circuit, approx_strategy, deg_profiles, circuit_info[circuit]['pit_loss'],
            early_cost=circuit_info[circuit].get('early_stop_cost', 0.0), check_limits=False
        )
        if total_time is not None:
            plan_b = {'strategy': approx_strategy, 'total_time': total_time}
        else:
            log.info(f" {circuit}: no Plan B, plans are dry-tyre only and the 2024 race wasn't "
                     f"({'->'.join(real_world['compound_sequence'])})")

    def format_plan(plan, label):
        if plan is None:
            return None
        risk = calculate_risk_score(
            circuit, plan['strategy'], deg_profiles, hazard_lookup, sc_probability
        )
        #RiskLevel is assigned in main(), once all risk scores exist
        return {
            'PlanLabel': label,
            'NumStops': len(plan['strategy']) - 1,
            'strategy': "->".join([f"{c}({l})" for c, l in plan['strategy']]),
            'PredictedTotalTime': round(plan['total_time'], 2),
            'RiskScore': risk
        }
    return{
        'CircuitName': circuit,
        'PlanA': format_plan(plan_a, 'A'),
        'PlanB': format_plan(plan_b, 'B'),
        'PlanC': format_plan(plan_c, 'C')
    }

"""MAIN PIPELINE
"""

def main():
    log.info("BOXBOX - Phase 5: Strategy Optimization Engine")
    log.info('-' * 50)

    degradation_df, feature_store, hazard_df, engineered_laps, raw_laps = load_all_data()
    deg_lookup, circuit_info, hazard_lookup = build_lookups(
        degradation_df, feature_store, hazard_df, engineered_laps, raw_laps
    )
    log.info(" Shortest stint allowed per circuit: "
             + ", ".join(f"{c} {info['min_stint']}" for c, info in sorted(circuit_info.items())))

    all_plans = []
    circuits = sorted(circuit_info.keys())

    log.info(f"\nGenerating strategies for {len(circuits)} circuits...")

    for circuit in circuits:
        result = build_plans(circuit, deg_lookup, circuit_info, hazard_lookup, raw_laps)

        if result is None:
            log.warning(f" {circuit}: No valid strategies found")
            continue
        for plan_key in ['PlanA', 'PlanB','PlanC']:
            plan = result[plan_key]
            if plan is None:
                continue
            row = {'CircuitName': circuit}
            row.update(plan)
            all_plans.append(row)

        log.info(f" {circuit}: Plan A = {result['PlanA']['strategy']} "
                f" ({result['PlanA']['PredictedTotalTime']}s, "
                f"risk={result['PlanA']['RiskScore']})")

    plans_df = pd.DataFrame(all_plans)

    '''Risk levels from the real score distribution (bottom third = Low,
    middle third = Medium, top third = High) instead of fixed cutoffs'''
    q1, q2 = plans_df['RiskScore'].quantile([0.33, 0.66])
    plans_df['RiskLevel'] = np.where(
        plans_df['RiskScore'] <= q1, 'Low',
        np.where(plans_df['RiskScore'] <= q2, 'Medium', 'High')
    )
    log.info(f"\nRisk cutoffs: Low <= {q1:.1f}, Medium <= {q2:.1f}, High above")

    #Saving outputs
    plans_path = os.path.join(BASE, 'data', 'processed', 'plan_abc.csv')
    plans_df.to_csv(plans_path, index=False)
    log.info(f"\nSaved: {plans_path} ({len(plans_df)} rows)")

    #Also save just Plan A per circuit as the "optimal_strategies" summary
    optimal_df = plans_df[plans_df['PlanLabel'] == 'A'].reset_index(drop=True)
    optimal_path = os.path.join(BASE, 'data', 'outputs', 'optimal_strategies.csv')
    optimal_df.to_csv(optimal_path, index=False)
    log.info(f" Saved: {optimal_path} ({len(optimal_df)} rows)")

    log.info("\n" + "-" * 50)
    log.info(" Phase 5 Summary")
    log.info("-" * 50)
    plans_per_circuit = plans_df.groupby('CircuitName')['PlanLabel'].nunique()
    log.info(f"\nCircuits with plans: {len(plans_per_circuit)}, "
            f"with all of A/B/C: {int((plans_per_circuit == 3).sum())}")
    log.info(f"\nRisk level breakdown (Plan A only):")
    log.info(optimal_df['RiskLevel'].value_counts().to_string())
    log.info(f"\nStop count breakdown (Plan A only):")
    log.info(optimal_df['NumStops'].value_counts().to_string())


if __name__ == '__main__':
    main()
